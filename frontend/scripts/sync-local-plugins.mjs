import fs from 'fs';
import path from 'path';

const WATCH = process.argv.includes('--watch');
const WATCH_INTERVAL_MS = 1000;
const IGNORED_ENTRIES = new Set([
  '.git',
  'node_modules',
  'dist',
  'build',
]);

const mappings = [
  {
    roots: ['/external-plugins', '/external-frontend-plugins'],
    target: '/app/src/local-plugins',
    splitDir: 'frontend',
    marker: '.omniplayr-local-frontend-links',
  },
];

const state = new Map();

function readPackageId(dir) {
  const pkgPath = path.join(dir, 'package.json');
  if (!fs.existsSync(pkgPath)) return null;
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    return typeof pkg.id === 'string' && pkg.id.trim() ? pkg.id.trim() : null;
  } catch {
    return null;
  }
}

function pluginSourceFromFolder(folder, splitDir) {
  const split = path.join(folder, splitDir);
  if (readPackageId(split)) return split;
  if (readPackageId(folder)) return folder;
  return null;
}

function discoverPlugins(root, splitDir) {
  if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) return [];

  const direct = pluginSourceFromFolder(root, splitDir);
  if (direct) return [{ id: readPackageId(direct), source: direct }];

  return fs.readdirSync(root, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => pluginSourceFromFolder(path.join(root, entry.name), splitDir))
    .filter(Boolean)
    .map(source => ({ id: readPackageId(source), source }))
    .filter(plugin => plugin.id);
}

function resetGeneratedLinks(target, marker) {
  fs.mkdirSync(target, { recursive: true });
  const markerPath = path.join(target, marker);
  if (!fs.existsSync(markerPath)) {
    fs.writeFileSync(markerPath, 'Generated by OmniPlayr dev startup.\n');
  }

  for (const entry of fs.readdirSync(target)) {
    if (entry === marker) continue;
    fs.rmSync(path.join(target, entry), { recursive: true, force: true });
  }
}

function snapshotDir(dir) {
  const parts = [];
  if (!fs.existsSync(dir)) return '';

  function walk(current, relative = '') {
    const entries = fs.readdirSync(current, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name));

    for (const entry of entries) {
      if (IGNORED_ENTRIES.has(entry.name)) continue;

      const full = path.join(current, entry.name);
      const rel = path.join(relative, entry.name);
      if (entry.isDirectory()) {
        walk(full, rel);
        continue;
      }
      if (!entry.isFile()) continue;
      const stat = fs.statSync(full);
      parts.push(`${rel}:${stat.size}:${Math.trunc(stat.mtimeMs)}`);
    }
  }

  walk(dir);
  return parts.join('|');
}

function syncDirIncremental(source, target, { prune = true } = {}) {
  fs.mkdirSync(target, { recursive: true });
  const sourceEntries = new Map();

  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    if (IGNORED_ENTRIES.has(entry.name)) continue;
    sourceEntries.set(entry.name, entry);
  }

  if (prune) {
    for (const entry of fs.readdirSync(target, { withFileTypes: true })) {
      if (IGNORED_ENTRIES.has(entry.name)) continue;
      if (!sourceEntries.has(entry.name)) {
        fs.rmSync(path.join(target, entry.name), { recursive: true, force: true });
      }
    }
  }

  for (const [name, entry] of sourceEntries) {
    const sourcePath = path.join(source, name);
    const targetPath = path.join(target, name);

    if (entry.isDirectory()) {
      syncDirIncremental(sourcePath, targetPath, { prune });
      continue;
    }

    if (!entry.isFile()) continue;

    const sourceStat = fs.statSync(sourcePath);
    let shouldCopy = true;
    if (fs.existsSync(targetPath)) {
      const targetStat = fs.statSync(targetPath);
      shouldCopy = sourceStat.size !== targetStat.size
        || Math.trunc(sourceStat.mtimeMs) !== Math.trunc(targetStat.mtimeMs);
    }

    if (shouldCopy) {
      fs.copyFileSync(sourcePath, targetPath);
      fs.utimesSync(targetPath, sourceStat.atime, sourceStat.mtime);
    }
  }
}

function discoverMappingPlugins(mapping) {
  const plugins = new Map();
  for (const root of mapping.roots) {
    for (const plugin of discoverPlugins(root, mapping.splitDir)) {
      plugins.set(plugin.id, plugin.source);
    }
  }
  return plugins;
}

function syncMapping(mapping, initial = false) {
  fs.mkdirSync(mapping.target, { recursive: true });
  const markerPath = path.join(mapping.target, mapping.marker);
  if (!fs.existsSync(markerPath)) {
    fs.writeFileSync(markerPath, 'Generated by OmniPlayr dev startup.\n');
  }

  const plugins = discoverMappingPlugins(mapping);
  const liveTargets = new Set([...plugins.keys(), mapping.marker]);

  for (const [id, source] of plugins) {
    const target = path.join(mapping.target, id);
    const snapshot = snapshotDir(source);
    const previous = state.get(target);
    if (!initial && previous === snapshot && fs.existsSync(target)) {
      continue;
    }

    syncDirIncremental(source, target, { prune: initial });
    state.set(target, snapshot);
    console.log(`[local-plugins] ${id}: synced ${source} -> ${target}`);
  }

  for (const entry of fs.readdirSync(mapping.target)) {
    if (liveTargets.has(entry)) continue;
    const target = path.join(mapping.target, entry);
    fs.rmSync(target, { recursive: true, force: true });
    state.delete(target);
    console.log(`[local-plugins] removed stale ${target}`);
  }
}

function syncAll(initial = false) {
  for (const mapping of mappings) {
    if (initial) resetGeneratedLinks(mapping.target, mapping.marker);
    syncMapping(mapping, initial);
  }
}

syncAll(true);

if (WATCH) {
  console.log(`[local-plugins] watching external plugins every ${WATCH_INTERVAL_MS}ms`);
  setInterval(() => {
    try {
      syncAll(false);
    } catch (error) {
      console.error(`[local-plugins] watch sync failed: ${error instanceof Error ? error.message : String(error)}`);
    }
  }, WATCH_INTERVAL_MS);
}
